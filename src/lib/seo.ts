import type { Metadata } from "next";
import { site } from "@/config/site";
import { boroughs } from "@/content/areas";

/**
 * Central place for everything search engines read: titles, canonical links, social cards
 * and structured data (JSON-LD). Pages call pageMetadata(); the layout emits the organisation data.
 */

export const siteUrl = site.url.replace(/\/$/, "");

/** True when the site is running on a real domain, not localhost, so it may be indexed. */
export const isLiveSite = !/localhost|127\.0\.0\.1|\.example/i.test(siteUrl);

/** When the site content last changed in a way worth telling search engines. Update when you edit pages. */
export const lastUpdated = "2026-10-25";

export const absoluteUrl = (path = "/") => (path === "/" ? siteUrl : `${siteUrl}${path}`);

type PageMeta = {
  title: string;
  description: string;
  /** Path of this page, e.g. "/about". Becomes the canonical URL. */
  path: string;
  /** Use the title exactly as written, without the "| <site name>" suffix. */
  absoluteTitle?: boolean;
  type?: "website" | "article";
  publishedTime?: string;
  noindex?: boolean;
};

/** The social-share picture, generated by src/app/opengraph-image.tsx. */
const shareImage = { url: "/opengraph-image", width: 1200, height: 630, alt: `${site.name}: foster care in London` };

export function pageMetadata({ title, description, path, absoluteTitle = false, type = "website", publishedTime, noindex = false }: PageMeta): Metadata {
  const fullTitle = absoluteTitle ? title : `${title} | ${site.name}`;
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: path },
    // Next replaces (not merges) nested objects, so repeat the site-wide values here.
    openGraph: {
      type,
      url: path,
      siteName: site.name,
      locale: "en_GB",
      title: fullTitle,
      description,
      images: [shareImage],
      ...(publishedTime ? { publishedTime } : {}),
    },
    twitter: { card: "summary_large_image", title: fullTitle, description, images: [shareImage.url] },
    ...(noindex ? { robots: { index: false, follow: true } } : {}),
  };
}

/* ---------- Structured data ---------- */

const socialUrls = () => Object.values(site.social).filter(Boolean);

export function organizationLd() {
  const { contact, regulation } = site;
  return {
    "@context": "https://schema.org",
    "@type": "Organization",
    "@id": `${siteUrl}/#organization`,
    name: site.name,
    alternateName: site.shortName,
    url: siteUrl,
    description: site.description,
    slogan: site.tagline,
    logo: absoluteUrl(site.logoMark),
    image: absoluteUrl("/opengraph-image"),
    email: contact.email,
    telephone: contact.phoneHref.replace("tel:", ""),
    address: {
      "@type": "PostalAddress",
      streetAddress: contact.addressParts.street,
      addressLocality: contact.addressParts.locality,
      addressRegion: contact.addressParts.region,
      postalCode: contact.addressParts.postcode,
      addressCountry: "GB",
    },
    areaServed: boroughs.filter((b) => b.covered).map((b) => ({ "@type": "AdministrativeArea", name: `${b.name}, London` })),
    contactPoint: [
      {
        "@type": "ContactPoint",
        contactType: "customer service",
        telephone: contact.phoneHref.replace("tel:", ""),
        email: contact.email,
        areaServed: "GB",
        availableLanguage: "English",
      },
    ],
    ...(socialUrls().length ? { sameAs: socialUrls() } : {}),
    ...(regulation.companyNumber ? { identifier: regulation.companyNumber } : {}),
  };
}

export function websiteLd() {
  return {
    "@context": "https://schema.org",
    "@type": "WebSite",
    "@id": `${siteUrl}/#website`,
    url: siteUrl,
    name: site.name,
    inLanguage: "en-GB",
    publisher: { "@id": `${siteUrl}/#organization` },
  };
}

export function breadcrumbLd(items: { name: string; path?: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: item.name,
      ...(item.path ? { item: absoluteUrl(item.path) } : {}),
    })),
  };
}

export function articleLd(post: { title: string; excerpt: string; date: string; slug: string }) {
  return {
    "@context": "https://schema.org",
    "@type": "BlogPosting",
    headline: post.title,
    description: post.excerpt,
    datePublished: post.date,
    dateModified: post.date,
    inLanguage: "en-GB",
    mainEntityOfPage: absoluteUrl(`/blog/${post.slug}`),
    url: absoluteUrl(`/blog/${post.slug}`),
    image: absoluteUrl("/opengraph-image"),
    author: { "@id": `${siteUrl}/#organization` },
    publisher: { "@id": `${siteUrl}/#organization` },
  };
}
